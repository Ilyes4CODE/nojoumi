"""Device installs, and nothing else.

This app exists for one contractual sentence, Art. 7.1: the free trial is
"مرة واحدة لكل جهاز" — once per device. That requires the server to recognise a
device it has seen before.

The identifier is a **random UUID generated by the app at first launch**. What it
deliberately is *not*:

  * not an advertising ID — forbidden for the Designed for Families programme
    the app enrols in (Art. 15.3);
  * not IMEI, serial, or MAC — unavailable to ordinary apps on modern Android
    anyway, and they identify a *person's* hardware;
  * not anything derived from the child (Art. 14).

The accepted limitation: a factory reset or a reinstall that clears app storage
produces a new UUID and therefore a new trial. Closing that would need a
persistent hardware identifier, which is exactly what Article 14 and Play policy
forbid. This trade-off is the right one — see open question Q18, still awaiting
the client's confirmation.
"""

from __future__ import annotations

import uuid

from django.conf import settings
from django.db import models


class Install(models.Model):
    """One installation of the app on one device."""

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)

    # Set when the install is linked to an account. Null until then, because the
    # trial can be claimed before the parent registers.
    parent = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="installs",
    )

    # Content-free diagnostics: which Android version and app build. Useful when
    # the developer has to reason about an OEM-specific failure (Art. 18).
    android_release = models.CharField(max_length=32, blank=True)
    device_model = models.CharField(max_length=64, blank=True)
    app_version = models.CharField(max_length=32, blank=True)

    created_at = models.DateTimeField(auto_now_add=True)
    last_seen_at = models.DateTimeField(auto_now=True)

    # Art. 7.1 — set the moment this device's one free trial is granted, and
    # never cleared.
    trial_consumed_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        indexes = [models.Index(fields=["trial_consumed_at"])]

    def __str__(self) -> str:
        return f"Install({self.id})"

    @property
    def trial_available(self) -> bool:
        return self.trial_consumed_at is None


class InstallAccount(models.Model):
    """One parent account signed in on one device.

    **Why a table and not a bigger `Install.parent`.** The client's rule of
    2026-08-28 was one account per phone; on 2026-09-25 they raised it to three,
    "but the subscription stays on the device". A single foreign key cannot hold
    three, and a trio of nullable columns would be a table drawn badly.

    `Install.parent` is kept as the **first** account bound to the device. It is
    what every existing query reads, it is what the trial and the activation code
    already record, and widening it to mean something new would have rewritten
    semantics in code that is working. The first binding writes both; the second
    and third write only here.

    **What this is not.** Articles 7.1 and the install binding both say plainly
    that the install id is a rule against casual account-swapping on a shared
    family phone, not a security boundary — clearing the app's data mints a new
    UUID and a fresh device. Raising one to three does not change that either
    way; it changes how many parents in one household can use the phone before
    they are told to stop.
    """

    install = models.ForeignKey(
        Install,
        on_delete=models.CASCADE,
        related_name="accounts",
    )
    parent = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name="install_bindings",
    )
    bound_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        verbose_name = "install account"
        verbose_name_plural = "install accounts"
        constraints = [
            models.UniqueConstraint(
                fields=["install", "parent"], name="one_row_per_account_per_install"
            )
        ]
        indexes = [models.Index(fields=["install", "bound_at"])]

    def __str__(self) -> str:
        return f"{self.parent_id} on {self.install_id}"
